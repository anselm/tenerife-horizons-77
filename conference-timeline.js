function addConferenceTimeline(){
 const d=conferenceTimeline;
 const slip=(e,i)=>`<article class="chronology-slip slip-${i}"><div class="chronology-date">${e.year} / ${e.city}</div><p><strong>${e.title}.</strong> ${e.body}</p></article>`;
 const p=d.plans;
 addSheet('conference-plans',p.title,'chronology-page plans-page',`<div class="chronology-heading"><span class="chronology-label">PROPOSALS / NOT PROPHECIES</span><h1>Already on<br><em>the drawing board.</em></h1></div><p class="chronology-intro">${p.intro}</p>${p.items.map((item,i)=>`<section class="plan-fragment plan-${i}"><span class="chronology-label">${item.label}</span><h2>${item.title}</h2><p>${item.body}</p></section>`).join('')}<aside class="chronology-note">${p.later}</aside><div class="chronology-sources">TENERIFE / CONFERENCE FILE / 1977</div>`);
 for(let side=0;side<2;side++){
  const rows=side?d.events.slice(8):d.events.slice(0,8);
 
  const head=side?`<span class="chronology-label">THE HINGE / HERE &amp; AFTER</span><h1 class="chronology-year">1977</h1><p class="chronology-subhead">and the rooms still to come.</p>`:`<span class="chronology-label">FROM THE CONFERENCE FILE / 1967–1976</span><h1>People kept<br><em>meeting.</em></h1>`;
  const intro=side?'From this year’s festivals and assemblies to the meetings now being prepared: the conversation travels on.':d.intro;
  addSheet(side?'conference-timeline-after':'conference-timeline',side?'1977 and the rooms still to come':d.title,'chronology-page chronology-'+side,`<div class="chronology-heading">${head}</div><p class="chronology-intro">${intro}</p><div class="chronology-stack">${rows.map(slip).join('')}</div>${side?`<aside class="chronology-note">${d.note}</aside>`:''}<div class="chronology-sources">${side?"PRÓXIMAS REUNIONES / DATES TO KEEP IN THE DIARY":"DEL ARCHIVO DE TRABAJO / PAPERS PASSED FROM HAND TO HAND"}</div>`);
 }

}
